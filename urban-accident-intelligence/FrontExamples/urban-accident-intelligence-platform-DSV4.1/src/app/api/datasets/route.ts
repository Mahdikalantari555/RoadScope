import { sql } from "drizzle-orm";
import { db } from "@/db";
import { jsonError, jsonOk } from "@/lib/api";
import { loadMetadata } from "@/lib/data";
import { SCENARIOS } from "@/lib/seed/generate";
import { ensureBootstrap } from "@/lib/bootstrap";

export const dynamic = "force-dynamic";

export async function GET() {
  try {
    await ensureBootstrap();
    const meta = await loadMetadata();
    const counts = await db.execute<{ dataset_id: number; records: number; verified: number }>(sql`
      select dataset_id, count(*)::int as records,
             sum(case when status = 'verified' then 1 else 0 end)::int as verified
      from accidents group by dataset_id
    `);
    const countMap = new Map(counts.rows.map((r) => [r.dataset_id, r]));
    return jsonOk({
      datasets: meta.datasets.map((d) => ({
        ...d,
        records: countMap.get(d.id)?.records ?? 0,
        verified: countMap.get(d.id)?.verified ?? 0,
        label: d.kind === "synthetic" ? "SYNTHETIC" : d.kind.toUpperCase(),
      })),
      scenarios: SCENARIOS,
      generator: {
        seed: meta.datasets[0]?.seed ?? null,
        reproducibility:
          "Datasets are generated by src/lib/seed with a fixed seed. The same seed reproduces the network, accidents, observations and injected quality defects.",
        projectedCrs:
          "Metric computations use a local equidistant projection centred on the study area; storage is EPSG:4326 with a documented PostGIS migration path.",
      },
    });
  } catch (error) {
    console.error("datasets failed", error);
    return jsonError("Unable to load dataset catalogue.", 500);
  }
}
