/** Idempotent bootstrap + synthetic dataset (re)generation. */
import { and, count, eq, inArray, sql } from "drizzle-orm";
import { db } from "@/db";
import {
  accidentCategories,
  accidents,
  basemapFeatures,
  datasetSources,
  environmentalObservations,
  roadNodes,
  roadSegments,
  severityLevels,
  trafficObservations,
  users,
} from "@/db/schema";
import { CATEGORIES, SEVERITIES } from "@/lib/domain";
import { bboxOf, PointGrid, type XY } from "@/lib/geo/geometry";
import { fromUtm } from "@/lib/geo/projection";
import { DEFAULT_DUP_OPTIONS, duplicateScore } from "@/lib/geo/duplicates";
import { generateDataset, type GeneratorConfig } from "@/lib/synthetic/generator";
import { hashPassword } from "./auth";
import { audit, getMeta, getNetwork, invalidateMeta, invalidateNetwork, snapWith } from "./data";
import { log } from "./http";

const g = globalThis as typeof globalThis & { __uaiSeed?: Promise<void> };

export function ensureSeeded(): Promise<void> {
  if (!g.__uaiSeed) {
    g.__uaiSeed = bootstrap().catch((e) => {
      g.__uaiSeed = undefined;
      throw e;
    });
  }
  return g.__uaiSeed;
}

async function bootstrap() {
  const [{ n: catCount }] = await db.select({ n: count() }).from(accidentCategories);
  if (catCount === 0) {
    await db.insert(accidentCategories).values(CATEGORIES.map((c) => ({ ...c }))).onConflictDoNothing();
    await db.insert(severityLevels).values(SEVERITIES.map((s) => ({ ...s }))).onConflictDoNothing();
    invalidateMeta();
  }
  const [{ n: userCount }] = await db.select({ n: count() }).from(users);
  if (userCount === 0) {
    await db
      .insert(users)
      .values([
        { email: "admin@uai.local", displayName: "Demo Administrator", role: "admin", passwordHash: hashPassword(process.env.DEMO_ADMIN_PASSWORD || "admin-demo") },
        { email: "citizen@uai.local", displayName: "Demo Citizen", role: "citizen", passwordHash: hashPassword(process.env.DEMO_CITIZEN_PASSWORD || "citizen-demo") },
      ])
      .onConflictDoNothing();
  }
  const [{ n: citizenDs }] = await db.select({ n: count() }).from(datasetSources).where(eq(datasetSources.kind, "citizen"));
  if (citizenDs === 0) {
    await db
      .insert(datasetSources)
      .values({ code: "CITIZEN", name: "Citizen reports (live)", kind: "citizen", description: "Reports submitted through the public reporting workflow.", license: "Contributors / platform terms", crs: "EPSG:4326 → EPSG:32633" })
      .onConflictDoNothing();
  }
  const [{ n: synth }] = await db
    .select({ n: count() })
    .from(datasetSources)
    .where(and(eq(datasetSources.kind, "synthetic"), sql`${datasetSources.config}->>'complete' = 'true'`));
  if (synth === 0) {
    log("info", "Seeding default synthetic dataset (scenario=mixed, seed=42)");
    await regenerateSynthetic({ scenario: "mixed", seed: 42 }, null);
  }
}

async function batchInsert<T>(rows: T[], size: number, fn: (chunk: T[]) => Promise<unknown>) {
  for (let i = 0; i < rows.length; i += size) await fn(rows.slice(i, i + size));
}

/** Replace the synthetic dataset (network, context, observations, accidents) with a freshly generated one. */
export async function regenerateSynthetic(partial: Partial<GeneratorConfig>, actorId: number | null) {
  const t0 = Date.now();
  const data = generateDataset(partial);
  const cfg = data.config;
  const meta = await getMeta();
  const code = `SYN-${cfg.scenario.toUpperCase()}-${cfg.seed}`;

  const old = await db.select({ id: datasetSources.id }).from(datasetSources).where(eq(datasetSources.kind, "synthetic"));
  if (old.length) await db.delete(datasetSources).where(inArray(datasetSources.id, old.map((o) => o.id)));
  invalidateNetwork();

  const [ds] = await db
    .insert(datasetSources)
    .values({
      code,
      name: `Synthetica — ${cfg.scenario} scenario (seed ${cfg.seed})`,
      kind: "synthetic",
      description: "Fully synthetic data generated by the reproducible UAI generator. Not real-world observations.",
      scenario: cfg.scenario,
      seed: cfg.seed,
      config: { ...cfg, injectedEffects: data.injectedEffects },
    })
    .returning({ id: datasetSources.id });

  const nodeRows = await db
    .insert(roadNodes)
    .values(
      data.nodes.map((n) => {
        const [lon, lat] = fromUtm(n.xy[0], n.xy[1]);
        return { datasetId: ds.id, x: n.xy[0], y: n.xy[1], lon, lat, degree: n.degree, signalized: n.signalized };
      }),
    )
    .returning({ id: roadNodes.id });
  const nodeId = nodeRows.map((r) => r.id);

  const segIds: number[] = [];
  await batchInsert(data.segments, 400, async (chunk) => {
    const res = await db
      .insert(roadSegments)
      .values(
        chunk.map((s) => {
          const bb = bboxOf(s.coords);
          return {
            datasetId: ds.id,
            name: s.name,
            roadClass: s.roadClass,
            speedLimit: s.speedLimit,
            lanes: s.lanes,
            lit: s.lit,
            surface: s.surface,
            lengthM: s.lengthM,
            fromNodeId: nodeId[s.from],
            toNodeId: nodeId[s.to],
            geom: s.coords.map((c) => fromUtm(c[0], c[1])),
            geomProj: s.coords,
            ...bb,
          };
        }),
      )
      .returning({ id: roadSegments.id });
    segIds.push(...res.map((r) => r.id));
  });

  await batchInsert(
    data.segments.flatMap((s, i) => s.aadt.map((a, k) => ({ datasetId: ds.id, segmentId: segIds[i], year: cfg.startYear + k, aadt: a, method: "synthetic log-normal by road class" }))),
    1000,
    (chunk) => db.insert(trafficObservations).values(chunk),
  );
  await db.insert(basemapFeatures).values(data.basemap.map((b) => ({ datasetId: ds.id, kind: b.kind, geom: [b.ring.map((c) => fromUtm(c[0], c[1]))] })));
  await batchInsert(data.weather, 1500, (chunk) =>
    db.insert(environmentalObservations).values(chunk.map((w) => ({ datasetId: ds.id, observedAt: new Date(w.t), condition: w.condition, precipitationMm: w.precipitationMm, visibilityM: w.visibilityM, temperatureC: w.temperatureC }))),
  );
  invalidateNetwork();

  // Accidents: snap reported coordinates to the new network; run duplicate detection on pending reports.
  const net = await getNetwork();
  const snapped = data.accidents.map((a) => snapWith(net, ...fromUtm(a.reportedXY[0], a.reportedXY[1])));
  const order = data.accidents.map((_, i) => i).sort((a, b) => data.accidents[a].reportedAt - data.accidents[b].reportedAt);
  const pts: XY[] = snapped.map((s) => [s.x, s.y]);
  const grid = new PointGrid(pts, 150);
  const rank = new Array<number>(order.length);
  order.forEach((idx, r) => (rank[idx] = r));
  const sevRank = (c: string) => SEVERITIES.find((s) => s.code === c)?.rank ?? 1;
  const dupOf = new Array<number | null>(data.accidents.length).fill(null);
  const dupScore = new Array<number | null>(data.accidents.length).fill(null);
  data.accidents.forEach((a, i) => {
    if (a.status === "duplicate" && a.truth.originalIndex !== undefined) {
      dupOf[i] = a.truth.originalIndex;
      dupScore[i] = 1;
      return;
    }
    if (a.status !== "reported") return;
    let best: { j: number; score: number } | null = null;
    for (const j of grid.within(pts[i], DEFAULT_DUP_OPTIONS.radius)) {
      if (j === i || rank[j] > rank[i] || data.accidents[j].status === "rejected") continue;
      const b = data.accidents[j];
      const s = duplicateScore(
        { id: i, x: pts[i][0], y: pts[i][1], t: a.occurredAt, category: a.category, severityRank: sevRank(a.severity) },
        { id: j, x: pts[j][0], y: pts[j][1], t: b.occurredAt, category: b.category, severityRank: sevRank(b.severity) },
      );
      if (s.dtMin <= DEFAULT_DUP_OPTIONS.windowMin && s.score >= DEFAULT_DUP_OPTIONS.threshold && (!best || s.score > best.score)) best = { j, score: s.score };
    }
    if (best) {
      dupOf[i] = best.j;
      dupScore[i] = best.score;
    }
  });

  const accIds: number[] = [];
  await batchInsert(
    data.accidents.map((a, i) => ({ a, i })),
    500,
    async (chunk) => {
      const res = await db
        .insert(accidents)
        .values(
          chunk.map(({ a, i }) => {
            const s = snapped[i];
            const [rlon, rlat] = fromUtm(a.reportedXY[0], a.reportedXY[1]);
            const flags = [...s.flags];
            if (dupOf[i] !== null && a.status === "reported") flags.push("possible_duplicate");
            if (a.reportedAt - a.occurredAt > 72 * 3600000) flags.push("late_report");
            return {
              datasetId: ds.id,
              trackingCode: `S${ds.id}-${i.toString(36).toUpperCase().padStart(4, "0")}`,
              occurredAt: new Date(a.occurredAt),
              reportedAt: new Date(a.reportedAt),
              categoryId: meta.catId.get(a.category)!,
              severityId: meta.sevId.get(a.severity)!,
              vehicles: a.vehicles,
              description: a.description,
              emergencyServices: a.emergency,
              status: a.status,
              reportedLon: rlon,
              reportedLat: rlat,
              lon: s.lon,
              lat: s.lat,
              x: s.x,
              y: s.y,
              segmentId: s.segmentId,
              snapDistanceM: s.snapDistanceM,
              duplicateScore: dupScore[i],
              qualityFlags: flags,
              weather: a.weather,
              lightCondition: a.light,
              isSynthetic: true,
              syntheticTruth: a.truth,
            };
          }),
        )
        .returning({ id: accidents.id });
      accIds.push(...res.map((r) => r.id));
    },
  );
  const updates = dupOf.map((d, i) => (d === null ? null : [accIds[i], accIds[d]] as const)).filter((x): x is readonly [number, number] => x !== null);
  if (updates.length)
    await db.execute(
      sql`update accidents a set duplicate_of_id = v.dup from (values ${sql.join(updates.map(([id, d]) => sql`(${id}::int, ${d}::int)`), sql`, `)}) as v(id, dup) where a.id = v.id`,
    );

  // Re-assign citizen reports to the new network.
  const citizen = await db
    .select({ id: accidents.id, lon: accidents.reportedLon, lat: accidents.reportedLat })
    .from(accidents)
    .innerJoin(datasetSources, eq(datasetSources.id, accidents.datasetId))
    .where(and(eq(datasetSources.kind, "citizen")));
  for (const c of citizen) {
    const s = snapWith(net, c.lon, c.lat);
    await db.update(accidents).set({ lon: s.lon, lat: s.lat, x: s.x, y: s.y, segmentId: s.segmentId, snapDistanceM: s.snapDistanceM }).where(eq(accidents.id, c.id));
  }
  await db.update(datasetSources).set({ config: { ...cfg, injectedEffects: data.injectedEffects, complete: true } }).where(eq(datasetSources.id, ds.id));
  invalidateNetwork();
  await audit(actorId, "dataset.regenerate", "dataset_source", ds.id, { code, config: cfg, records: data.accidents.length, ms: Date.now() - t0 });
  log("info", "Synthetic dataset generated", { code, accidents: data.accidents.length, segments: data.segments.length, ms: Date.now() - t0 });
  return { datasetId: ds.id, code, accidents: data.accidents.length, segments: data.segments.length };
}
